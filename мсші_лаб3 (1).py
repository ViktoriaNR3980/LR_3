import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score

# 1. ЗАВАНТАЖЕННЯ
df = pd.read_csv('IrisData_full.csv', header=None)
df_shuffled = df.sample(frac=1, random_state=42).reset_index(drop=True)

# Беремо перші дві колонки (Довжина і Ширина чашолистка) для малювання
X_2d = df_shuffled.iloc[:, [0, 1]].values
# Беремо всі 4 колонки для точного прогнозу і навчання моделі
X_full = df_shuffled.iloc[:, :-1].values
y_raw = df_shuffled.iloc[:, 4].values

classes_unique = np.unique(y_raw)
y = np.zeros(len(y_raw))
for i, cl in enumerate(classes_unique):
    y[y_raw == cl] = i

scaler = StandardScaler()
X_2d_scaled = scaler.fit_transform(X_2d)
scaler_full = StandardScaler()
X_full_scaled = scaler_full.fit_transform(X_full)

X_train, X_test, y_train, y_test = train_test_split(X_2d_scaled, y, test_size=0.2, random_state=42)
X_train_f, X_test_f, _, _ = train_test_split(X_full_scaled, y, test_size=0.2, random_state=42)

#  кольори для всіх графіків
colors = ['royalblue', 'mediumseagreen', 'darkviolet']

# --- РИСУНОК 1 ---
plt.figure(figsize=(8, 5))
for i, cl_name in enumerate(classes_unique):
    mask = (y == i)
    plt.scatter(X_2d_scaled[mask, 0], X_2d_scaled[mask, 1], color=colors[i], label=f'Клас: {cl_name}', s=60, alpha=0.9)
plt.title('Графік 1: Вихідні нормалізовані дані', fontsize=12, fontweight='bold')
plt.xlabel('Довжина чашолистка', fontsize=10)
plt.ylabel('Ширина чашолистка', fontsize=10)
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.savefig('fig1.png', dpi=300, bbox_inches='tight')

# --- РИСУНОК 2 ---
plt.figure(figsize=(8, 5))
plt.scatter(X_train[:, 0], X_train[:, 1], color='dodgerblue', marker='o', alpha=0.6, s=60, label='Навчальні дані')
plt.scatter(X_test[:, 0], X_test[:, 1], color='crimson', marker='^', s=90, edgecolor='black', label='Тестові дані')
plt.title('Графік 2: Розподіл на навчальну та тестову вибірки', fontsize=12, fontweight='bold')
plt.xlabel('Довжина чашолистка', fontsize=10)
plt.ylabel('Ширина чашолистка', fontsize=10)
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.savefig('fig2.png', dpi=300, bbox_inches='tight')

# --- РИСУНОК 3 ---
k_values = list(range(3, 16))
train_accs, test_accs = [], []
for k in k_values:
    knn = KNeighborsClassifier(n_neighbors=k)
    knn.fit(X_train_f, y_train)
    train_accs.append(accuracy_score(y_train, knn.predict(X_train_f)))
    test_accs.append(accuracy_score(y_test, knn.predict(X_test_f)))

best_test_acc = max(test_accs)
best_k = k_values[test_accs.index(best_test_acc)]

plt.figure(figsize=(9, 5))
plt.plot(k_values, train_accs, marker='o', color='dodgerblue', linewidth=2, label='Train Accuracy')
plt.plot(k_values, test_accs, marker='s', color='crimson', linewidth=2, label='Test Accuracy')
plt.axvline(x=best_k, color='forestgreen', linestyle='--', linewidth=2, label=f'Найкраще K = {best_k}')
plt.title('Графік 3: Залежність точності від параметра K', fontsize=12, fontweight='bold')
plt.xlabel('Кількість сусідів (K)', fontsize=10)
plt.ylabel('Точність', fontsize=10)
plt.xticks(k_values)
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.savefig('fig3.png', dpi=300, bbox_inches='tight')

# --- РИСУНОК 4 ---
best_knn = KNeighborsClassifier(n_neighbors=best_k)
best_knn.fit(X_train_f, y_train)
y_pred = best_knn.predict(X_test_f)

plt.figure(figsize=(8, 5))

plt.scatter(X_train[:, 0], X_train[:, 1], color='lightgray', alpha=0.5, label='Навчальні дані', s=50)


for i, cl_name in enumerate(classes_unique):
    mask = (y_pred == i)
    plt.scatter(X_test[mask, 0], X_test[mask, 1], color=colors[i], marker='o', edgecolor='black', s=90, label=f'Прогноз: {cl_name}')

plt.title(f'Графік 4: Результати прогнозування (при K={best_k})', fontsize=12, fontweight='bold')
plt.xlabel('Довжина чашолистка', fontsize=10)
plt.ylabel('Ширина чашолистка', fontsize=10)
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.savefig('fig4.png', dpi=300, bbox_inches='tight')

plt.show()